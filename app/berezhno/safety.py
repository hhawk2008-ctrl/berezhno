"""Проверка текста на кризисные сигналы и темы, с которыми сервис не работает.

Ключевые слова — первая линия: срабатывают без ИИ и мгновенно. ИИ дополнительно оценивает тему при составлении плана.
"""
import re

CRISIS = [
    r"\bсуицид", r"\bпокончить\s+с\s+собой", r"\bпокончу\s+с\s+собой", r"\bубить\s+себя", r"\bубью\s+себя",
    r"\bне\s+хочу\s+(больше\s+)?жить", r"\bхочу\s+умереть", r"\bсвести\s+сч[её]ты", r"\bсведу\s+сч[её]ты",
    r"\bлучше\s+бы\s+меня\s+не\s+было", r"\bсамоповрежд", r"\bпорезать\s+себя", r"\bрезать\s+себя",
    r"\bпричинить\s+себе\s+вред", r"\bнет\s+смысла\s+жить",
]

FORBIDDEN = [
    # зависимости
    r"\bбросить\s+(пить|курить)", r"\bне\s+пить\b", r"\bалкогол", r"\bнаркот", r"\bзависимост",
    r"\bказино", r"\bигромани", r"\bставк\w*\s+на\s+спорт", r"\bсигарет", r"\bкурени", r"\bвейп",
    # вес и питание
    r"\bпохуд", r"\bсбросить\s+(\d+\s*)?(кг|килограм\w*|вес)", r"\bнабрать\s+(\d+\s*)?(кг|килограм\w*|вес)",
    r"\bлишн\w*\s+вес", r"\bдиет", r"\bкалори", r"\b\d+\s*кг\b", r"\bпитани", r"\bпереедан",
    # долги
    r"\bдолг(и|а|ов|ам|ами|ах|у|ом)?\b", r"\bкредит", r"\bзайм", r"\bипотек", r"\bколлектор", r"\bбанкрот",
]

_crisis = re.compile("|".join(CRISIS), re.I)
_forbidden = re.compile("|".join(FORBIDDEN), re.I)


def classify(text: str) -> str:
    """crisis, forbidden или ok."""
    if _crisis.search(text):
        return "crisis"
    if _forbidden.search(text):
        return "forbidden"
    return "ok"
